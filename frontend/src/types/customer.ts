export type CustomerType =
    | 'INDIVIDUAL'
    | 'BUSINESS';

export type CustomerStatus =
    | 'ACTIVE'
    | 'INACTIVE'
    | 'ARCHIVED';

export type AddressType =
    | 'HOME'
    | 'BUSINESS'
    | 'BILLING'
    | 'SHIPPING'
    | 'OTHER';

export type ActivityType =
    | 'CUSTOMER_CREATED'
    | 'CUSTOMER_UPDATED'
    | 'CUSTOMER_ARCHIVED'
    | 'CUSTOMER_ACTIVATED'
    | 'CUSTOMER_DEACTIVATED'
    | 'ADDRESS_ADDED'
    | 'ADDRESS_UPDATED'
    | 'ADDRESS_DELETED'
    | 'NOTE_ADDED'
    | 'DOCUMENT_UPLOADED'
    | 'DOCUMENT_DELETED';

/* =========================================================
   CUSTOMER
========================================================= */

export interface Customer {
    /**
     * Internal UUID.
     *
     * Used by the application and API for relationships
     * and routes such as /customers/:id.
     *
     * This should not normally be displayed to users.
     */
    id: string;

    /**
     * System-generated sequential customer number.
     *
     * Example:
     * 1 -> CUS-000001
     *
     * This value is generated by the backend/database
     * and must not be editable by users.
     */
    customerNumber: number;

    type: CustomerType;

    firstName: string | null;
    lastName: string | null;
    businessName: string | null;

    email: string;
    phone: string;

    status: CustomerStatus;

    createdAt: string;
    updatedAt: string;
}

/* =========================================================
   CUSTOMER LIST
========================================================= */

export interface CustomerListResponse {
    success: boolean;

    data: Customer[];

    meta: {
        page: number;
        limit: number;
        total: number;
        totalPages: number;
    };
}

