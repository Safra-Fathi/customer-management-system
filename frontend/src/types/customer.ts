/* =========================================================
   CUSTOMER DISPLAY HELPERS
========================================================= */

/**
 * Converts the database customer number into the
 * customer-facing reference used throughout CustomerFlow.
 *
 * Examples:
 * 1    -> CUS-000001
 * 25   -> CUS-000025
 * 1250 -> CUS-001250
 */
export const formatCustomerId = (
    customerNumber: number,
): string => {
    return `CUS-${String(customerNumber).padStart(
        6,
        '0',
    )}`;
};

/**
 * Returns the appropriate display name depending
 * on whether the record represents an individual
 * or a business.
 */
export const getCustomerDisplayName = (
    customer: Pick<
        Customer,
        | 'type'
        | 'firstName'
        | 'lastName'
        | 'businessName'
    >,
): string => {
    if (customer.type === 'BUSINESS') {
        return (
            customer.businessName?.trim() ||
            'Unnamed business'
        );
    }

    const fullName = [
        customer.firstName,
        customer.lastName,
    ]
        .filter(Boolean)
        .join(' ')
        .trim();

    return fullName || 'Unnamed customer';
};